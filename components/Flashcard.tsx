            className="group relative cursor-pointer min-h-[380px] rounded-3xl border border-stone-300/90 bg-white p-6 sm:p-8 shadow-sm hover:shadow-md transition-all duration-300 flex flex-col justify-between"
          >
            {/* FRONT OF CARD */}
